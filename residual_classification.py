# Fast path. classify_remaining_words above builds ONE regex alternation out
# of every candidate word (unresolved_words can be 150k+ entries at this
# stage of the pipeline). Python's re module backtracks rather than compiling
# a trie/Aho-Corasick automaton, so a pattern that size is brutally slow to
# both compile and match -- fine for a small band-sized batch, not fine for
# a full-corpus pass. This path does the identical replacement (same \b
# semantics, same case-insensitivity, same three outcomes) via tokenize +
# set/dict lookup instead, which is O(1) per token regardless of how many
# thousands of words are in play. Used by parallel_classify.py.
_TOKEN_RE = re.compile(r'(\w+)')


def prepare_classification_sets(unresolved_words):
    """One-time (per call) prep: lowercased LANGUAGE_LABELS dict + the set of
    words that should become NONWORD, given the current JARGON_TERMS /
    LANGUAGE_LABELS. Cheap -- just dict/set construction, no regex."""
    lang_dict = {w.lower(): label for w, label in LANGUAGE_LABELS.items()}
    nonword_set = {
        w.lower() for w in unresolved_words
        if w.lower() not in JARGON_TERMS
        and w.lower() not in LANGUAGE_LABELS
        and not w.isdigit()
    }
    return lang_dict, nonword_set


def classify_text(text, lang_dict, nonword_set):
    """Apply the jargon/language-label/NONWORD classification to one string.
    Splits on \\w+ runs (same boundary behavior as the \\b-bounded regex
    above -- an apostrophe still ends a token), and for each token checks
    lang_dict/nonword_set membership instead of testing against a giant
    compiled alternation."""
    if not isinstance(text, str) or not text:
        return text
    parts = _TOKEN_RE.split(text)
    for i in range(1, len(parts), 2):
        low = parts[i].lower()
        if low in lang_dict:
            parts[i] = lang_dict[low]
        elif low in nonword_set:
            parts[i] = 'NONWORD'
    return ''.join(parts)


def classify_remaining_words_fast(series, unresolved_words):
    """Single-threaded fast-path equivalent of classify_remaining_words --
    same output, no giant regex. Use parallel_classify.py's
    parallel_classify_remaining_words for a full-df run; this is here for
    small runs / sanity-checking the two paths agree."""
    lang_dict, nonword_set = prepare_classification_sets(unresolved_words)
    return series.map(lambda t: classify_text(t, lang_dict, nonword_set))