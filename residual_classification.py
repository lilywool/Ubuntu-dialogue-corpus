def _build_patterns():
    lang_pattern = re.compile(
        r'\b(?:' + '|'.join(re.escape(w) for w in sorted(LANGUAGE_LABELS, key=len, reverse=True)) + r')\b',
        re.IGNORECASE,
    ) if LANGUAGE_LABELS else None
    return lang_pattern


def classify_remaining_words(series, unresolved_words):
    """Final pass over whatever's still unresolved after lexicon updates +
    glued-match promotion. `unresolved_words` is the current residual
    vocabulary (already lowercased) this pass should act on -- pass in
    latin_extended | plain | has_digit (or their mismatch_* counterparts)
    from the review cells, unioned together.

    - words in JARGON_TERMS: left untouched in the text (handled by adding
      them to the lexicon instead -- see JARGON_TERMS docstring above)
    - words in LANGUAGE_LABELS: replaced with their language label
    - standalone digit-only tokens: left untouched
    - everything else remaining: replaced with NONWORD
    """
    lang_pattern = _build_patterns()

    nonword_terms = [
        w for w in unresolved_words
        if w.lower() not in JARGON_TERMS
        and w.lower() not in LANGUAGE_LABELS
        and not w.isdigit()
    ]
    nonword_pattern = re.compile(
        r'\b(?:' + '|'.join(re.escape(w) for w in sorted(nonword_terms, key=len, reverse=True)) + r')\b',
        re.IGNORECASE,
    ) if nonword_terms else None

    out = series
    if lang_pattern is not None:
        out = out.str.replace(lang_pattern, lambda m: LANGUAGE_LABELS[m.group(0).lower()], regex=True)
    if nonword_pattern is not None:
        out = out.str.replace(nonword_pattern, 'NONWORD', regex=True)
    return out


